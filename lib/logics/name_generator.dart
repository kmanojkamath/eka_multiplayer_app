int generateRandomNameNumber() {
  final random = Random();
  return (random.nextInt(creatures.length) + 1) * 100 +
      random.nextInt(professions.length) +
      1;
}

String getNameFromNumber(int? number) {
  if (number == null) return "Unknown Player";
  return '${professions[(number % 100) - 1]} ${creatures[(number ~/ 100) - 1]}';
}
